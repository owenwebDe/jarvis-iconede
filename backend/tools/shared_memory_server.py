# ── Prospects & Leads Tools ──────────────────────────────────────────────────


@mcp.tool()
def prospect_save(
    company_name: str,
    contact_name: str = "",
    email: str = "",
    phone: str = "",
    website: str = "",
    country: str = "Global",
    city: str = "",
    industry: str = "",
    source_agent: str = "LeadResearchAgent",
    status: str = "new",
    lead_score: int = 50,
    notes: str = "",
) -> dict:
    """Save or update a business lead/prospect into shared persistent memory.

    Use this tool whenever LeadResearchAgent discovers new businesses or OutreachAgent
    updates contact status.
    """
    try:
        return shared_memory.upsert_prospect(
            company_name=company_name,
            contact_name=contact_name or None,
            email=email or None,
            phone=phone or None,
            website=website or None,
            country=country or "Global",
            city=city or None,
            industry=industry or None,
            source_agent=source_agent,
            status=status,
            lead_score=lead_score,
            notes=notes or None,
        )
    except Exception as exc:
        logger.exception("Error saving prospect")
        return {"error": str(exc)}


@mcp.tool()
def prospect_search(
    query: str = "",
    status: str = "",
    country: str = "",
    industry: str = "",
    limit: int = 20,
) -> dict:
    """Search and query stored prospects in shared memory.

    Allows filtering by keyword, status ('new', 'qualified', 'contacted', 'converted'),
    country, or industry.
    """
    try:
        results = shared_memory.search_prospects(
            query=query or None,
            status=status or None,
            country=country or None,
            industry=industry or None,
            limit=limit,
        )
        return {"prospects": results, "count": len(results)}
    except Exception as exc:
        return {"error": str(exc)}



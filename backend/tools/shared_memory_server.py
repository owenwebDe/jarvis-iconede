# ── Board Meeting Tools ──────────────────────────────────────────────────────


@mcp.tool()
def board_meeting_start(
    title: str = "Executive Board Meeting",
    agenda: str = "",
    participants: Any = None,
    participants_json: Any = None,
    meeting_id: str = "",
    topic: str = "",
) -> dict:
    """Start a board meeting session between Jarvis and specialist agents.
    
    participants: list of agent names (e.g. ['LeadResearchAgent', 'CreativeAgent', 'AdsAgent'])
    """
    try:
        if not meeting_id:
            meeting_id = f"meeting-{uuid.uuid4().hex[:8]}"
        if not agenda and topic:
            agenda = topic
        parsed_participants = []
        raw_p = participants if participants is not None else participants_json
        if isinstance(raw_p, list):
            parsed_participants = [str(p) for p in raw_p]
        elif isinstance(raw_p, str) and raw_p.strip():
            try:
                p = json.loads(raw_p)
                parsed_participants = [str(x) for x in p] if isinstance(p, list) else [str(p)]
            except Exception:
                parsed_participants = [x.strip() for x in raw_p.split(",") if x.strip()]
        
        if not parsed_participants:
            parsed_participants = ["Jarvis", "LeadResearchAgent", "CreativeAgent"]

        return shared_memory.start_board_meeting(
            meeting_id=meeting_id,
            title=title or "Executive Board Meeting",
            agenda=agenda or "Strategic Growth & Operations",
            participants=parsed_participants,
        )
    except Exception as exc:
        return {"error": str(exc)}


@mcp.tool()
def board_meeting_speak(
    speaker: str = "",
    message: str = "",
    statement: str = "",
    agent: str = "",
    meeting_id: str = "",
) -> dict:
    """Record an agent's deliberation statement or recommendation in a board meeting."""
    try:
        spk = speaker or agent or "SpecialistAgent"
        msg = message or statement or ""
        if not meeting_id:
            db = shared_memory.get_db_session()
            try:
                m = db.query(shared_memory.BoardMeetingModel).filter(
                    shared_memory.BoardMeetingModel.status == "in_progress"
                ).order_by(shared_memory.BoardMeetingModel.created_at.desc()).first()
                meeting_id = m.meeting_id if m else f"meeting-{uuid.uuid4().hex[:8]}"
            finally:
                db.close()

        return shared_memory.add_board_meeting_transcript(
            meeting_id=meeting_id,
            speaker=spk,
            message=msg,
        )
    except Exception as exc:
        return {"error": str(exc)}


@mcp.tool()
def board_meeting_conclude(
    action_plan: str = "",
    summary: str = "",
    meeting_id: str = "",
) -> dict:
    """Conclude a board meeting and record the final agreed action plan."""
    try:
        plan = action_plan or summary or "Action plan agreed and finalized."
        if not meeting_id:
            db = shared_memory.get_db_session()
            try:
                m = db.query(shared_memory.BoardMeetingModel).filter(
                    shared_memory.BoardMeetingModel.status == "in_progress"
                ).order_by(shared_memory.BoardMeetingModel.created_at.desc()).first()
                meeting_id = m.meeting_id if m else "active-meeting"
            finally:
                db.close()

        return shared_memory.conclude_board_meeting(
            meeting_id=meeting_id,
            action_plan=plan,
        )
    except Exception as exc:
        return {"error": str(exc)}


@mcp.tool()
def board_meeting_get(meeting_id: str) -> dict:
    """Retrieve full details, agenda, participants, and transcript of a board meeting."""
    try:
        meeting = shared_memory.get_board_meeting_details(meeting_id)
        if not meeting:
            return {"error": f"Board meeting '{meeting_id}' not found"}
        return meeting
    except Exception as exc:
        return {"error": str(exc)}


